-- ZankoSwap: "I'm looking for this book" lists and paid featured listings.
-- Run in Supabase Dashboard -> SQL Editor, after 23. Safe to run more than once.

-- =====================================================================
-- 1) Wanted books: each person keeps a private list (max 10) of books they
--    are looking for; the app shows matching listings.
-- =====================================================================
create table if not exists public.book_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null check (char_length(btrim(title)) between 2 and 120),
  created_at timestamptz not null default now()
);
create index if not exists book_requests_user_idx on public.book_requests (user_id);

alter table public.book_requests enable row level security;
revoke all on public.book_requests from anon, authenticated;
grant select, insert, delete on public.book_requests to authenticated;

drop policy if exists "book_requests_own_read" on public.book_requests;
create policy "book_requests_own_read" on public.book_requests
for select to authenticated using (user_id = auth.uid());
drop policy if exists "book_requests_own_insert" on public.book_requests;
create policy "book_requests_own_insert" on public.book_requests
for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "book_requests_own_delete" on public.book_requests;
create policy "book_requests_own_delete" on public.book_requests
for delete to authenticated using (user_id = auth.uid());

create or replace function public.limit_book_requests()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (select count(*) from public.book_requests where user_id = new.user_id) >= 10 then
    raise exception 'wanted_limit' using errcode = 'P0001';
  end if;
  return new;
end;
$$;
drop trigger if exists limit_book_requests on public.book_requests;
create trigger limit_book_requests
before insert on public.book_requests
for each row execute function public.limit_book_requests();

drop trigger if exists enforce_clean_text on public.book_requests;
create trigger enforce_clean_text
before insert or update on public.book_requests
for each row execute function public.enforce_clean_text('title');

-- =====================================================================
-- 2) Featured listings: shown first on the home screen until a date.
--    Only the admin (after checking the payment) can set that date.
-- =====================================================================
alter table public.listings add column if not exists featured_until timestamptz;

create or replace function public.protect_listing_featured()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null
     or public.is_admin()
     or current_setting('zankoswap.featuring', true) = 'on' then
    return new;
  end if;
  if tg_op = 'INSERT' then
    new.featured_until := null;
  else
    new.featured_until := old.featured_until;
  end if;
  return new;
end;
$$;
drop trigger if exists protect_listing_featured on public.listings;
create trigger protect_listing_featured
before insert or update on public.listings
for each row execute function public.protect_listing_featured();

-- Weekly price, changeable by the admin in the app's ad price editor.
insert into public.ad_prices (placement, price_per_week_iqd)
values ('featured', 2000)
on conflict (placement) do nothing;

create table if not exists public.featured_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  listing_id text not null,
  days integer not null default 7 check (days in (7, 14)),
  price_iqd integer not null default 0,
  receipt text not null default '' check (char_length(receipt) between 3 and 300),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);
create unique index if not exists featured_requests_one_pending
  on public.featured_requests (listing_id) where status = 'pending';

alter table public.featured_requests enable row level security;
revoke all on public.featured_requests from anon, authenticated;
grant select, insert, delete on public.featured_requests to authenticated;

drop policy if exists "featured_read_own_or_admin" on public.featured_requests;
create policy "featured_read_own_or_admin" on public.featured_requests
for select to authenticated using (user_id = auth.uid() or public.is_admin());

drop policy if exists "featured_insert_own_listing" on public.featured_requests;
create policy "featured_insert_own_listing" on public.featured_requests
for insert to authenticated
with check (
  user_id = auth.uid()
  and status = 'pending'
  and reviewed_at is null
  and exists (
    select 1 from public.listings l
    where l.id::text = listing_id and l."sellerId" = auth.uid() and l.status = 'active'
  )
);

drop policy if exists "featured_delete_own_pending_or_admin" on public.featured_requests;
create policy "featured_delete_own_pending_or_admin" on public.featured_requests
for delete to authenticated
using ((user_id = auth.uid() and status = 'pending') or public.is_admin());

-- The price is always worked out on the server.
create or replace function public.set_featured_price()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  weekly integer;
begin
  select price_per_week_iqd into weekly from public.ad_prices where placement = 'featured';
  new.price_iqd := coalesce(weekly, 2000) * (new.days / 7);
  return new;
end;
$$;
drop trigger if exists set_featured_price on public.featured_requests;
create trigger set_featured_price
before insert on public.featured_requests
for each row execute function public.set_featured_price();

create or replace function public.review_featured(request_id bigint, approve boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  req public.featured_requests%rowtype;
begin
  if not public.is_admin() then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  select * into req from public.featured_requests
  where id = request_id and status = 'pending'
  for update;
  if not found then
    raise exception 'request_not_found' using errcode = 'P0001';
  end if;

  update public.featured_requests
  set status = case when approve then 'approved' else 'rejected' end,
      reviewed_at = now()
  where id = request_id;

  if approve then
    perform set_config('zankoswap.featuring', 'on', true);
    update public.listings
    set featured_until = greatest(coalesce(featured_until, now()), now())
                         + make_interval(days => req.days)
    where id::text = req.listing_id;
    perform set_config('zankoswap.featuring', 'off', true);
  end if;
end;
$$;
revoke all on function public.review_featured(bigint, boolean) from public, anon;
grant execute on function public.review_featured(bigint, boolean) to authenticated;

-- Payment receipts (ads and featured): at most 30 photos per person, so
-- nobody can fill the private receipts storage.
create or replace function public.my_receipt_file_count()
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select count(*)::integer from storage.objects
  where bucket_id = 'ad-receipts'
    and (storage.foldername(name))[1] = auth.uid()::text;
$$;
revoke all on function public.my_receipt_file_count() from public, anon;
grant execute on function public.my_receipt_file_count() to authenticated;

drop policy if exists "ad_receipts_insert_own" on storage.objects;
create policy "ad_receipts_insert_own" on storage.objects
for insert to authenticated
with check (
  bucket_id = 'ad-receipts'
  and (storage.foldername(name))[1] = auth.uid()::text
  and public.my_receipt_file_count() < 30
);

-- =====================================================================
-- 3) Admin statistics, now with the most wanted books and featured counts.
-- =====================================================================
create or replace function public.admin_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  return jsonb_build_object(
    'users_total', (select count(*) from auth.users),
    'users_7d', (select count(*) from auth.users where created_at > now() - interval '7 days'),
    'verified_users', (select count(*) from public.profiles where is_verified),
    'pending_verifications', (select count(*) from public.verification_requests where status = 'pending'),
    'listings_active', (select count(*) from public.listings where status = 'active'),
    'listings_7d', (select count(*) from public.listings where "createdAt" > now() - interval '7 days'),
    'places_total', (select count(*) from public.services),
    'chats_7d', (select count(distinct "chatId") from public.messages where "createdAt" > now() - interval '7 days'),
    'messages_7d', (select count(*) from public.messages where "createdAt" > now() - interval '7 days'),
    'views_total', (select coalesce(sum(views), 0) from public.listing_stats),
    'featured_active', (select count(*) from public.listings where featured_until > now()),
    'pending_featured', (select count(*) from public.featured_requests where status = 'pending'),
    'top_universities', (
      select coalesce(jsonb_agg(t), '[]'::jsonb) from (
        select "universityName" as name, count(*) as total
        from public.listings
        where status = 'active' and coalesce("universityName", '') <> ''
        group by 1 order by 2 desc limit 5
      ) t
    ),
    'top_listings', (
      select coalesce(jsonb_agg(t), '[]'::jsonb) from (
        select l.title as name, s.views as total
        from public.listing_stats s
        join public.listings l on l.id::text = s.listing_id
        order by s.views desc limit 5
      ) t
    ),
    'top_wanted', (
      select coalesce(jsonb_agg(t), '[]'::jsonb) from (
        select min(btrim(title)) as name, count(*) as total
        from public.book_requests
        group by lower(btrim(title))
        order by 2 desc limit 5
      ) t
    )
  );
end;
$$;
revoke all on function public.admin_stats() from public, anon;
grant execute on function public.admin_stats() to authenticated;

select 'done' as result;
