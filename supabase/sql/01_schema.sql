-- Listings used by the Home feed and My Listings screen.
create table if not exists public.listings (
  id bigint generated by default as identity primary key,
  "sellerId" uuid not null references auth.users(id) on delete cascade,
  "sellerName" text not null default 'Student',
  title text not null,
  description text not null default '',
  type text not null default 'book',
  "transactionType" text not null default 'free',
  "priceIQD" integer not null default 0,
  condition text not null default 'good',
  edition text,
  subject text,
  semester integer,
  images jsonb not null default '[]'::jsonb,
  "pdfUrl" text,
  "cityId" text not null default '',
  "universityId" text not null default '',
  "universityName" text not null default '',
  "collegeId" text not null default '',
  "departmentId" text not null default '',
  stage integer not null default 1,
  "stageLabel" text not null default '',
  status text not null default 'active',
  "viewCount" integer not null default 0,
  "favoriteCount" integer not null default 0,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

alter table public.listings enable row level security;
drop policy if exists "listings_read" on public.listings;
create policy "listings_read" on public.listings for select to public using (true);
drop policy if exists "listings_insert_own" on public.listings;
create policy "listings_insert_own" on public.listings for insert to authenticated
with check (auth.uid() = "sellerId");
drop policy if exists "listings_update_own" on public.listings;
create policy "listings_update_own" on public.listings for update to authenticated
using (auth.uid() = "sellerId") with check (auth.uid() = "sellerId");
drop policy if exists "listings_delete_own" on public.listings;
create policy "listings_delete_own" on public.listings for delete to authenticated
using (auth.uid() = "sellerId");

