-- Enable Realtime for tables used by the Flutter streams.
-- This block is safe to run more than once and skips tables not created yet.
do $$
declare
  item record;
begin
  for item in
    select table_name
    from information_schema.tables
    where table_schema = 'public'
      and table_name in ('listings', 'services', 'institutions', 'research', 'exam_papers', 'messages', 'ad_campaigns')
  loop
    if not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = item.table_name
    ) then
      execute format('alter publication supabase_realtime add table public.%I', item.table_name);
    end if;
  end loop;
end $$;


-- Institutions directory used by the Schools, Institutes, Vocational and Colleges tabs.
create table if not exists public.institutions (
  id bigint generated by default as identity primary key,
  type text not null default 'college',
  "nameKu" text not null default '',
  "nameEn" text not null default '',
  city text not null default '',
  "descriptionKu" text not null default '',
  "descriptionEn" text not null default '',
  "websiteUrl" text not null default '',
  "instagramUrl" text not null default '',
  "facebookUrl" text not null default '',
  phone text not null default '',
  address text not null default '',
  "logoUrl" text not null default '',
  active boolean not null default true,
  "durationYears" integer not null default 0,
  "admissionAfterGrade9" boolean not null default false,
  "studyLanguage" text not null default '',
  specialties text not null default '',
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

alter table public.institutions enable row level security;
drop policy if exists "institutions_read_active" on public.institutions;
create policy "institutions_read_active" on public.institutions for select to public using (active = true);
drop policy if exists "institutions_insert_authenticated" on public.institutions;
create policy "institutions_insert_authenticated" on public.institutions for insert to authenticated with check (true);
drop policy if exists "institutions_update_authenticated" on public.institutions;
create policy "institutions_update_authenticated" on public.institutions for update to authenticated using (true) with check (true);

-- Add institutions to Realtime after the table exists.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'institutions'
  ) then
    alter publication supabase_realtime add table public.institutions;
  end if;
end $$;


