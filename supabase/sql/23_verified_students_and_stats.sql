-- ZankoSwap: verified students (student ID checked by the admin) and statistics.
-- Run in Supabase Dashboard -> SQL Editor, after 22. Safe to run more than once.

-- =====================================================================
-- 1) Verified badge on profiles. Only the admin (through review_verification
--    or admin_set_verified) can turn it on or off.
-- =====================================================================
alter table public.profiles add column if not exists is_verified boolean not null default false;
grant select (is_verified) on public.profiles to authenticated;

create or replace function public.protect_profile_verified()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null
     or public.is_admin()
     or current_setting('zankoswap.verifying', true) = 'on' then
    return new;
  end if;
  if tg_op = 'INSERT' then
    new.is_verified := false;
  else
    new.is_verified := old.is_verified;
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_verified on public.profiles;
create trigger protect_profile_verified
before insert or update on public.profiles
for each row execute function public.protect_profile_verified();

-- Anyone (also visitors without an account) may ask "is this seller verified?".
create or replace function public.is_user_verified(uid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select is_verified from public.profiles where id = uid), false);
$$;
revoke all on function public.is_user_verified(uuid) from public;
grant execute on function public.is_user_verified(uuid) to anon, authenticated;

-- =====================================================================
-- 2) Verification requests: one pending request per person.
-- =====================================================================
create table if not exists public.verification_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  image_path text not null default '',
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);
create unique index if not exists verification_requests_one_pending
  on public.verification_requests (user_id) where status = 'pending';
create index if not exists verification_requests_status_idx
  on public.verification_requests (status, created_at);

alter table public.verification_requests enable row level security;
revoke all on public.verification_requests from anon, authenticated;
grant select, insert, delete on public.verification_requests to authenticated;

drop policy if exists "verification_read_own_or_admin" on public.verification_requests;
create policy "verification_read_own_or_admin" on public.verification_requests
for select to authenticated using (user_id = auth.uid() or public.is_admin());

drop policy if exists "verification_insert_own" on public.verification_requests;
create policy "verification_insert_own" on public.verification_requests
for insert to authenticated
with check (
  user_id = auth.uid()
  and status = 'pending'
  and reviewed_at is null
  and image_path like auth.uid()::text || '/%'
);

drop policy if exists "verification_delete_own_pending_or_admin" on public.verification_requests;
create policy "verification_delete_own_pending_or_admin" on public.verification_requests
for delete to authenticated
using ((user_id = auth.uid() and status = 'pending') or public.is_admin());

-- Private storage for student ID photos: only the owner and the admin see
-- them. The app deletes the photo as soon as the admin decides.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('student-ids', 'student-ids', false, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

-- At most 3 photos at a time per person, so nobody can fill the storage.
create or replace function public.my_student_id_file_count()
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select count(*)::integer from storage.objects
  where bucket_id = 'student-ids'
    and (storage.foldername(name))[1] = auth.uid()::text;
$$;
revoke all on function public.my_student_id_file_count() from public, anon;
grant execute on function public.my_student_id_file_count() to authenticated;

drop policy if exists "student_ids_insert_own" on storage.objects;
create policy "student_ids_insert_own" on storage.objects
for insert to authenticated
with check (
  bucket_id = 'student-ids'
  and (storage.foldername(name))[1] = auth.uid()::text
  and public.my_student_id_file_count() < 3
);

drop policy if exists "student_ids_read_own_or_admin" on storage.objects;
create policy "student_ids_read_own_or_admin" on storage.objects
for select to authenticated
using (
  bucket_id = 'student-ids'
  and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin())
);

drop policy if exists "student_ids_delete_own_or_admin" on storage.objects;
create policy "student_ids_delete_own_or_admin" on storage.objects
for delete to authenticated
using (
  bucket_id = 'student-ids'
  and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin())
);

-- Admin decision. Returns the photo path so the app can delete the photo.
create or replace function public.review_verification(request_id bigint, approve boolean)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  req public.verification_requests%rowtype;
begin
  if not public.is_admin() then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  select * into req from public.verification_requests
  where id = request_id and status = 'pending'
  for update;
  if not found then
    raise exception 'request_not_found' using errcode = 'P0001';
  end if;

  update public.verification_requests
  set status = case when approve then 'approved' else 'rejected' end,
      reviewed_at = now(),
      image_path = ''
  where id = request_id;

  if approve then
    perform set_config('zankoswap.verifying', 'on', true);
    update public.profiles set is_verified = true where id = req.user_id;
    perform set_config('zankoswap.verifying', 'off', true);
  end if;
  return req.image_path;
end;
$$;
revoke all on function public.review_verification(bigint, boolean) from public, anon;
grant execute on function public.review_verification(bigint, boolean) to authenticated;

-- Admin can also remove a badge later (for example after abuse).
create or replace function public.admin_set_verified(uid uuid, verified boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  perform set_config('zankoswap.verifying', 'on', true);
  update public.profiles set is_verified = verified where id = uid;
  perform set_config('zankoswap.verifying', 'off', true);
end;
$$;
revoke all on function public.admin_set_verified(uuid, boolean) from public, anon;
grant execute on function public.admin_set_verified(uuid, boolean) to authenticated;

-- =====================================================================
-- 3) Listing views. Kept in their own table (not on listings) so a view
--    does not send a live update to every open app.
-- =====================================================================
create table if not exists public.listing_stats (
  listing_id text primary key,
  views integer not null default 0,
  updated_at timestamptz not null default now()
);
alter table public.listing_stats enable row level security;
revoke all on public.listing_stats from anon, authenticated;
grant select on public.listing_stats to anon, authenticated;

drop policy if exists "listing_stats_read_all" on public.listing_stats;
create policy "listing_stats_read_all" on public.listing_stats
for select to anon, authenticated using (true);

-- Counts a view of an active listing. The seller's own views do not count.
create or replace function public.count_listing_view(listing_id text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1 from public.listings l
    where l.id::text = listing_id
      and l.status = 'active'
      and l.moderation_hidden = false
      and l."sellerId" is distinct from auth.uid()
  ) then
    return;
  end if;
  insert into public.listing_stats as s (listing_id, views)
  values (listing_id, 1)
  on conflict (listing_id) do update
  set views = s.views + 1, updated_at = now();
end;
$$;
revoke all on function public.count_listing_view(text) from public;
grant execute on function public.count_listing_view(text) to anon, authenticated;

-- =====================================================================
-- 4) Numbers for the admin panel.
-- =====================================================================
create or replace function public.admin_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  return jsonb_build_object(
    'users_total', (select count(*) from auth.users),
    'users_7d', (select count(*) from auth.users where created_at > now() - interval '7 days'),
    'verified_users', (select count(*) from public.profiles where is_verified),
    'pending_verifications', (select count(*) from public.verification_requests where status = 'pending'),
    'listings_active', (select count(*) from public.listings where status = 'active'),
    'listings_7d', (select count(*) from public.listings where "createdAt" > now() - interval '7 days'),
    'places_total', (select count(*) from public.services),
    'chats_7d', (select count(distinct "chatId") from public.messages where "createdAt" > now() - interval '7 days'),
    'messages_7d', (select count(*) from public.messages where "createdAt" > now() - interval '7 days'),
    'views_total', (select coalesce(sum(views), 0) from public.listing_stats),
    'top_universities', (
      select coalesce(jsonb_agg(t), '[]'::jsonb) from (
        select "universityName" as name, count(*) as total
        from public.listings
        where status = 'active' and coalesce("universityName", '') <> ''
        group by 1 order by 2 desc limit 5
      ) t
    ),
    'top_listings', (
      select coalesce(jsonb_agg(t), '[]'::jsonb) from (
        select l.title as name, s.views as total
        from public.listing_stats s
        join public.listings l on l.id::text = s.listing_id
        order by s.views desc limit 5
      ) t
    )
  );
end;
$$;
revoke all on function public.admin_stats() from public, anon;
grant execute on function public.admin_stats() to authenticated;

