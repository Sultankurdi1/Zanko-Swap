-- ZankoSwap: in-app admin panel, seller ratings and app error reports.
-- Run once in Supabase Dashboard -> SQL Editor, after policy_reset_all_tables.sql.
-- Safe to run more than once.

-- 1) Admins can read and clear reports from the in-app admin panel.
drop policy if exists "content_reports_admin_read" on public.content_reports;
create policy "content_reports_admin_read" on public.content_reports
for select to authenticated using (public.is_admin());
drop policy if exists "content_reports_admin_delete" on public.content_reports;
create policy "content_reports_admin_delete" on public.content_reports
for delete to authenticated using (public.is_admin());

drop policy if exists "user_reports_admin_read" on public.user_reports;
create policy "user_reports_admin_read" on public.user_reports
for select to authenticated using (public.is_admin());
drop policy if exists "user_reports_admin_delete" on public.user_reports;
create policy "user_reports_admin_delete" on public.user_reports
for delete to authenticated using (public.is_admin());

-- 2) Seller ratings: 1 to 5 stars, one rating per person per seller, and only
--    between two people who have actually chatted.
create table if not exists public.seller_ratings (
  id bigint generated by default as identity primary key,
  rater_id uuid not null references auth.users(id) on delete cascade,
  seller_id uuid not null references auth.users(id) on delete cascade,
  stars smallint not null check (stars between 1 and 5),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint seller_ratings_not_self check (rater_id <> seller_id),
  constraint seller_ratings_once unique (rater_id, seller_id)
);
create index if not exists seller_ratings_seller_idx on public.seller_ratings (seller_id);
alter table public.seller_ratings enable row level security;

create or replace function public.have_chatted(user_a uuid, user_b uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.chats c
    where (c."buyerId" = user_a and c."sellerId" = user_b)
       or (c."buyerId" = user_b and c."sellerId" = user_a)
  );
$$;
revoke all on function public.have_chatted(uuid, uuid) from public, anon;
grant execute on function public.have_chatted(uuid, uuid) to authenticated;

drop policy if exists "seller_ratings_read_own" on public.seller_ratings;
create policy "seller_ratings_read_own" on public.seller_ratings
for select to authenticated using (auth.uid() = rater_id or public.is_admin());
drop policy if exists "seller_ratings_insert_own" on public.seller_ratings;
create policy "seller_ratings_insert_own" on public.seller_ratings
for insert to authenticated
with check (auth.uid() = rater_id and public.have_chatted(rater_id, seller_id));
drop policy if exists "seller_ratings_update_own" on public.seller_ratings;
create policy "seller_ratings_update_own" on public.seller_ratings
for update to authenticated
using (auth.uid() = rater_id)
with check (auth.uid() = rater_id and public.have_chatted(rater_id, seller_id));
drop policy if exists "seller_ratings_delete_own" on public.seller_ratings;
create policy "seller_ratings_delete_own" on public.seller_ratings
for delete to authenticated using (auth.uid() = rater_id or public.is_admin());

create or replace function public.seller_rating_summary(seller uuid)
returns table (average numeric, total bigint)
language sql
stable
security definer
set search_path = public
as $$
  select round(avg(stars)::numeric, 1), count(*)
  from public.seller_ratings
  where seller_id = seller;
$$;
revoke all on function public.seller_rating_summary(uuid) from public;
grant execute on function public.seller_rating_summary(uuid) to anon, authenticated;

-- 3) App error reports, written only through a size- and rate-limited function.
create table if not exists public.app_errors (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  message text not null,
  stack text not null default '',
  platform text not null default '',
  app_version text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists app_errors_created_idx on public.app_errors (created_at desc);
alter table public.app_errors enable row level security;
revoke all on public.app_errors from anon, authenticated;
grant select, delete on public.app_errors to authenticated;

drop policy if exists "app_errors_admin_read" on public.app_errors;
create policy "app_errors_admin_read" on public.app_errors
for select to authenticated using (public.is_admin());
drop policy if exists "app_errors_admin_delete" on public.app_errors;
create policy "app_errors_admin_delete" on public.app_errors
for delete to authenticated using (public.is_admin());

create or replace function public.log_app_error(
  message text,
  stack text default '',
  platform text default '',
  app_version text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if (select count(*) from public.app_errors where created_at > now() - interval '1 hour') >= 500 then
    return;
  end if;
  insert into public.app_errors (user_id, message, stack, platform, app_version)
  values (
    auth.uid(),
    left(coalesce(message, ''), 1000),
    left(coalesce(stack, ''), 4000),
    left(coalesce(platform, ''), 40),
    left(coalesce(app_version, ''), 40)
  );
end;
$$;
revoke all on function public.log_app_error(text, text, text, text) from public;
grant execute on function public.log_app_error(text, text, text, text) to anon, authenticated;

do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    execute $sql$
      select cron.unschedule(jobid) from cron.job where jobname = 'zankoswap-trim-app-errors'
    $sql$;
    perform cron.schedule(
      'zankoswap-trim-app-errors',
      '15 4 * * *',
      $job$delete from public.app_errors where created_at < now() - interval '30 days'$job$
    );
  end if;
exception when others then
  raise notice 'Could not schedule app error cleanup.';
end $$;
