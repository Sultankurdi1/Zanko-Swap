    update public.exam_papers set "createdAt" = created_at where "createdAt" is null;
    alter table public.exam_papers drop column created_at;
  end if;
end $$;
alter table public.exam_papers enable row level security;
drop policy if exists "exam_papers_public_read" on public.exam_papers;
create policy "exam_papers_public_read" on public.exam_papers for select to public using (true);
drop policy if exists "exam_papers_insert_own" on public.exam_papers;
create policy "exam_papers_insert_own" on public.exam_papers for insert to authenticated with check (auth.uid() = "authorId");
drop policy if exists "exam_papers_update_own" on public.exam_papers;
create policy "exam_papers_update_own" on public.exam_papers for update to authenticated using (auth.uid() = "authorId") with check (auth.uid() = "authorId");
drop policy if exists "exam_papers_delete_own" on public.exam_papers;
create policy "exam_papers_delete_own" on public.exam_papers for delete to authenticated using (auth.uid() = "authorId");

create table if not exists public.service_updates (
  id bigint generated by default as identity primary key,
  "serviceId" bigint not null references public.services(id) on delete cascade,
  "ownerId" uuid not null references auth.users(id) on delete cascade,
  title text not null,
  body text not null default '',
  "imageUrl" text,
  "createdAt" timestamptz not null default now()
);
alter table public.service_updates enable row level security;
drop policy if exists "service_updates_public_read" on public.service_updates;
create policy "service_updates_public_read" on public.service_updates for select to public using (true);
drop policy if exists "service_updates_insert_owner" on public.service_updates;
create policy "service_updates_insert_owner" on public.service_updates for insert to authenticated with check (auth.uid() = "ownerId" and exists (select 1 from public.services s where s.id = "serviceId" and s."ownerId" = auth.uid()));
drop policy if exists "service_updates_update_owner" on public.service_updates;
create policy "service_updates_update_owner" on public.service_updates for update to authenticated using (auth.uid() = "ownerId") with check (auth.uid() = "ownerId");
drop policy if exists "service_updates_delete_owner" on public.service_updates;
create policy "service_updates_delete_owner" on public.service_updates for delete to authenticated using (auth.uid() = "ownerId");

create table if not exists public.chats (
  id text primary key,
  "buyerId" uuid not null references auth.users(id) on delete cascade,
  "sellerId" uuid not null references auth.users(id) on delete cascade,
  "listingId" bigint not null references public.listings(id) on delete cascade,
  "lastMessage" text not null default '',
  "lastMessageAt" timestamptz,
  "updatedAt" timestamptz not null default now(),
  check ("buyerId" <> "sellerId")
);
alter table public.chats enable row level security;
drop policy if exists "chats_participants_read" on public.chats;
create policy "chats_participants_read" on public.chats for select to authenticated using (auth.uid() = "buyerId" or auth.uid() = "sellerId");
drop policy if exists "chats_participants_insert" on public.chats;
create policy "chats_participants_insert" on public.chats for insert to authenticated with check (auth.uid() = "buyerId" or auth.uid() = "sellerId");
drop policy if exists "chats_participants_update" on public.chats;
create policy "chats_participants_update" on public.chats for update to authenticated using (auth.uid() = "buyerId" or auth.uid() = "sellerId") with check (auth.uid() = "buyerId" or auth.uid() = "sellerId");

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  "chatId" text not null references public.chats(id) on delete cascade,
  "senderId" uuid not null references auth.users(id) on delete cascade,
  text text not null,
  type text not null default 'text',
  "isRead" boolean not null default false,
  "createdAt" timestamptz not null default now()
);
alter table public.messages enable row level security;
drop policy if exists "messages_participants_read" on public.messages;
create policy "messages_participants_read" on public.messages for select to authenticated using (exists (select 1 from public.chats c where c.id = "chatId" and (auth.uid() = c."buyerId" or auth.uid() = c."sellerId")));
drop policy if exists "messages_participants_insert" on public.messages;
create policy "messages_participants_insert" on public.messages for insert to authenticated with check (auth.uid() = "senderId" and exists (select 1 from public.chats c where c.id = "chatId" and (auth.uid() = c."buyerId" or auth.uid() = c."sellerId")));
drop policy if exists "messages_participants_update" on public.messages;
create policy "messages_participants_update" on public.messages for update to authenticated using (exists (select 1 from public.chats c where c.id = "chatId" and (auth.uid() = c."buyerId" or auth.uid() = c."sellerId"))) with check (exists (select 1 from public.chats c where c.id = "chatId" and (auth.uid() = c."buyerId" or auth.uid() = c."sellerId")));

-- Realtime is optional; enable only after the tables exist.
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='research') then alter publication supabase_realtime add table public.research; end if;
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='exam_papers') then alter publication supabase_realtime add table public.exam_papers; end if;
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='messages') then alter publication supabase_realtime add table public.messages; end if;
exception when undefined_object then null;
end $$;


