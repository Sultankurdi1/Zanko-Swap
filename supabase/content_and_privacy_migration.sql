-- Run in Supabase Dashboard -> SQL Editor.

-- If an earlier build created the camelCase table, preserve its data by
-- renaming it before creating/using the canonical snake_case table.
do $$ begin
  if to_regclass('public."examPapers"') is not null
     and to_regclass('public.exam_papers') is null then
    alter table public."examPapers" rename to exam_papers;
  end if;
end $$;

create table if not exists public.research (
  id bigint generated by default as identity primary key,
  "authorId" uuid not null references auth.users(id) on delete cascade,
  "authorName" text not null default 'Student',
  title text not null,
  description text not null default '',
  "linkOrContent" text not null default '',
  "universityId" text not null default '',
  "universityName" text not null default '',
  "collegeId" text not null default '',
  "departmentId" text not null default '',
  "stageLabel" text not null default '',
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
-- Canonical fields used by the Flutter research submission form.
alter table public.research add column if not exists stage text not null default '';
alter table public.research add column if not exists file_url text not null default '';
alter table public.research add column if not exists "authorId" uuid;
alter table public.research add column if not exists "createdAt" timestamptz not null default now();
do $$ begin
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'research' and column_name = 'author_id') then
    update public.research set "authorId" = author_id where "authorId" is null;
    alter table public.research drop column author_id;
  end if;
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'research' and column_name = 'created_at') then
    update public.research set "createdAt" = created_at where "createdAt" is null;
    alter table public.research drop column created_at;
  end if;
end $$;
alter table public.research enable row level security;
drop policy if exists "research_public_read" on public.research;
create policy "research_public_read" on public.research for select to public using (true);
drop policy if exists "research_insert_own" on public.research;
create policy "research_insert_own" on public.research for insert to authenticated with check (auth.uid() = "authorId");
drop policy if exists "research_update_own" on public.research;
create policy "research_update_own" on public.research for update to authenticated using (auth.uid() = "authorId") with check (auth.uid() = "authorId");
drop policy if exists "research_delete_own" on public.research;
create policy "research_delete_own" on public.research for delete to authenticated using (auth.uid() = "authorId");

create table if not exists public.exam_papers (
