-- Chat reporting and user blocking. Run in Supabase SQL Editor.
create table if not exists public.user_blocks (
  id bigint generated by default as identity primary key,
  blocker_id uuid not null references auth.users(id) on delete cascade,
  blocked_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint user_blocks_not_self check (blocker_id <> blocked_id),
  constraint user_blocks_unique_pair unique (blocker_id, blocked_id)
);

alter table public.user_blocks enable row level security;
drop policy if exists user_blocks_read_own on public.user_blocks;
create policy user_blocks_read_own on public.user_blocks for select to authenticated
  using (auth.uid() = blocker_id);
drop policy if exists user_blocks_create_own on public.user_blocks;
create policy user_blocks_create_own on public.user_blocks for insert to authenticated
  with check (auth.uid() = blocker_id and blocker_id <> blocked_id);
drop policy if exists user_blocks_delete_own on public.user_blocks;
create policy user_blocks_delete_own on public.user_blocks for delete to authenticated
  using (auth.uid() = blocker_id);

create table if not exists public.user_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reported_user_id uuid not null references auth.users(id) on delete cascade,
  chat_id text,
  reason text not null check (reason in ('harassment', 'spam', 'inappropriate', 'other')),
  details text,
  created_at timestamptz not null default now(),
  constraint user_reports_not_self check (reporter_id <> reported_user_id)
);

alter table public.user_reports enable row level security;
drop policy if exists user_reports_create_own on public.user_reports;
create policy user_reports_create_own on public.user_reports for insert to authenticated
  with check (auth.uid() = reporter_id and reporter_id <> reported_user_id);
-- Reports are private to moderators/service role; client users cannot read them.

-- Enforce blocks at the database boundary so alternate clients cannot bypass the UI.
create or replace function public.chat_users_blocked(user_a uuid, user_b uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.user_blocks b
    where (b.blocker_id = user_a and b.blocked_id = user_b)
       or (b.blocker_id = user_b and b.blocked_id = user_a)
  );
$$;
revoke all on function public.chat_users_blocked(uuid, uuid) from public;
grant execute on function public.chat_users_blocked(uuid, uuid) to authenticated;

drop policy if exists messages_participants_insert on public.messages;
drop policy if exists "messages own insert" on public.messages;
create policy messages_participants_insert on public.messages for insert to authenticated
  with check (
    auth.uid() = "senderId"
    and exists (
      select 1 from public.chats c
      where c.id = "chatId"
        and (auth.uid() = c."buyerId" or auth.uid() = c."sellerId")
        and not public.chat_users_blocked(
          c."buyerId", c."sellerId"
        )
    )
  );
